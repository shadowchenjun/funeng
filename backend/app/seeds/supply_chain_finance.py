def _recommendations(debt_ratio: float, cash_flow: str, overdue_count: int, industry: float) -> list[str]:
    """根据风险指标生成固定的改进建议"""
    recs = []
    if debt_ratio >= 50:
        recs.append("建议降低负债率至50%以下")
    if cash_flow != "良好":
        recs.append("加强现金流管理，优化回款周期")
    if overdue_count > 0:
        recs.append(f"近一年逾期{overdue_count}次，建议按期履约以提升信用")
    if industry < 75:
        recs.append("扩大经营规模、延伸产业链以提升抗风险能力")
    return recs or ["信用状况良好，保持现有经营策略"]


def seed_supply_chain_finance(db: Session) -> bool:
    """
    写入供应链金融默认数据（融资订单 / 应收账款 / 保单 / 信用评估）。

    每张表仅在为空时写入。返回是否写入了任何数据。
    """
    seeded = False

    if not db.query(FinancingOrder).first():
        for (order_no, applicant, product, amount, ratio, rate, term,
             status, apply_date, collateral, risk) in _FINANCING_ORDERS:
            applied = D(apply_date)
            db.add(FinancingOrder(
                order_no=order_no, applicant=applicant, product=product,
                amount=amount, financed_amount=round(amount * ratio, 2),
                rate=rate, term=term, status=status, apply_date=applied,
                expected_return=applied + timedelta(days=term),
                collateral=collateral, risk_level=risk,
            ))
        seeded = True

    if not db.query(Receivable).first():
        for (invoice_no, creditor, debtor, amount, paid,
             issue_date, due_date, status, risk) in _RECEIVABLES:
            db.add(Receivable(
                invoice_no=invoice_no, creditor=creditor, debtor=debtor,
                amount=amount, paid_amount=paid, issue_date=D(issue_date),
                due_date=D(due_date), status=status, risk_level=risk,
            ))
        seeded = True

    if not db.query(InsurancePolicy).first():
        for (policy_no, holder, type_, crop, area, coverage, premium_rate, deductible_rate,
             start_date, end_date, status, claims_count, claims_amount) in _INSURANCE_POLICIES:
            db.add(InsurancePolicy(
                policy_no=policy_no, holder=holder, type=type_, crop=crop, area=area,
                coverage=coverage, premium=round(coverage * premium_rate, 2),
                deductible=round(coverage * deductible_rate, 2),
                start_date=D(start_date), end_date=D(end_date), status=status,
                claims_count=claims_count, claims_amount=claims_amount,
            ))
        seeded = True

    if not db.query(CreditAssessment).first():
        for (name, entity_type, score, assessed, fin, op, mgmt, ind,
             overdue, debt_ratio, cash_flow) in _CREDIT_ASSESSMENTS:
            assessed_on = D(assessed)
            # 固定的历史轨迹：半年前 -12 分，一年前 -25 分
            history = [
                {"date": assessed, "score": score, "level": credit_level(score), "event": "年度评估"},
                {"date": (assessed_on - timedelta(days=182)).isoformat(), "score": score - 12,
                 "level": credit_level(score - 12), "event": "半年度评估"},
                {"date": (assessed_on - timedelta(days=365)).isoformat(), "score": score - 25,
                 "level": credit_level(score - 25), "event": "年度评估"},
            ]
            db.add(CreditAssessment(
                entity_name=name, entity_type=entity_type, credit_score=score,
                level=credit_level(score), assessment_date=assessed_on,
                next_review=assessed_on + timedelta(days=365),
                factor_financial=fin, factor_operation=op,
                factor_management=mgmt, factor_industry=ind,
                overdue_count=overdue, debt_ratio=debt_ratio, cash_flow=cash_flow,
                history=history,
                recommendations=_recommendations(debt_ratio, cash_flow, overdue, ind),
            ))
        seeded = True

    if seeded:
        db.commit()
    return seeded
